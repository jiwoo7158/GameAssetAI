REQUIRED_DIRS = ["docs", "skills", "scripts", "tests", "templates",
                 "templates/skill", "tests/smoke", "tests/workspace", "workspace-template"]


def validate_repository(root: Path) -> list[str]:
    errors = []
    for relative in REQUIRED_DIRS:
        path = root / relative
        if is_link(path) or not path.is_dir():
            errors.append(f"Expected a real directory: {relative}")
    for relative in REQUIRED:
        path = root / relative
        if is_link(path) or any(is_link(root / p) for p in path.relative_to(root).parents):
            errors.append(f"Linked repository path is not supported: {relative}")
        elif not path.is_file():
            errors.append(f"Missing or non-file path: {relative}")
        else:
            try:
                if not path.read_text(encoding="utf-8-sig").strip():
                    errors.append(f"Empty file: {relative}")
            except (OSError, UnicodeError) as exc:
                errors.append(f"Cannot read {relative}: {exc}")
    if not errors:
        errors.extend(validate_workspace(root / "workspace-template", template_mode=True))
        for skill in sorted((root / "skills").iterdir()):
            if skill.is_dir():
                try:
                    skill_files(skill)
                except (OSError, UnicodeError, ValueError, SyntaxError) as exc:
                    errors.append(f"Skill {skill.name}: {exc}")
    return errors


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    try:
        errors = validate_repository(root)
    except OSError as exc:
        errors = [str(exc)]

    if errors:
        print("Repository validation failed.")
        for item in errors:
            print(f"  {item}")
        return 1

    print("Repository structure OK.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
